import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

print("Libraries imported successfully")

from google.colab import files

uploaded = files.upload()

df = pd.read_excel("Online Retail.xlsx")

print("First 5 rows:")
display(df.head())

print("Last 5 rows:")
display(df.tail())

print("Dataset shape:")
print(df.shape)

print("Dataset information:")
df.info()

print("Statistical summary:")
display(df.describe())

# Missing values
print("Missing values:")
print(df.isnull().sum())

# Duplicate rows
print("Duplicates:", df.duplicated().sum())

# Unique customers
print("Unique customers:", df["CustomerID"].nunique())

# Unique invoices
print("Unique invoices:", df["InvoiceNo"].nunique())

df = df.drop_duplicates()

# Convert date to datetime
df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"])

# Remove missing customer IDs
df = df.dropna(subset=["CustomerID"])

# Convert customer ID to integer
df["CustomerID"] = df["CustomerID"].astype(int)

# Remove invalid prices and quantities
df = df[df["UnitPrice"] > 0]
df = df[df["Quantity"] != 0]

# Create revenue column
df["Revenue"] = df["Quantity"] * df["UnitPrice"]

display(df.head())

total_revenue = df["Revenue"].sum()

total_customers = df["CustomerID"].nunique()

total_orders = df["InvoiceNo"].nunique()

print("Total Revenue:", total_revenue)
print("Total Customers:", total_customers)
print("Total Orders:", total_orders)

average_order_value = total_revenue / total_orders

print("Average Order Value:", average_order_value)

snapshot_date = df["InvoiceDate"].max() + pd.Timedelta(days=1)

rfm = df.groupby("CustomerID").agg({
    "InvoiceDate": lambda x: (snapshot_date - x.max()).days,
    "InvoiceNo": "nunique",
    "Revenue": "sum"
})

rfm.columns = ["Recency", "Frequency", "Monetary"]

display(rfm.head())

top_customers = rfm.sort_values(
    "Monetary", ascending=False
).head(10)

display(top_customers)

rfm["CustomerSegment"] = np.where(
    rfm["Monetary"] >= rfm["Monetary"].quantile(0.90),
    "High Value",
    np.where(
        rfm["Frequency"] >= rfm["Frequency"].median(),
        "Regular",
        "Low Value"
    )
)

print(rfm["CustomerSegment"].value_counts())

customer_orders = df.groupby("CustomerID")["InvoiceNo"].nunique()

repeat_customers = (customer_orders > 1).sum()

repeat_purchase_rate = (
    repeat_customers / len(customer_orders)
) * 100

print("Repeat Customers:", repeat_customers)
print("Repeat Purchase Rate:", round(repeat_purchase_rate, 2), "%")

# Keep genuine purchase transactions for retention
purchases = df[
    (df["Quantity"] > 0) &
    (~df["InvoiceNo"].astype(str).str.startswith("C"))
].copy()

purchases["InvoiceMonth"] = (
    purchases["InvoiceDate"].dt.to_period("M")
)

# First purchase month for each customer
purchases["CohortMonth"] = (
    purchases.groupby("CustomerID")["InvoiceMonth"]
    .transform("min")
)

purchases["CohortIndex"] = (
    (purchases["InvoiceMonth"].dt.year -
     purchases["CohortMonth"].dt.year) * 12
    +
    (purchases["InvoiceMonth"].dt.month -
     purchases["CohortMonth"].dt.month)
    + 1
)

cohort_data = purchases.groupby(
    ["CohortMonth", "CohortIndex"]
)["CustomerID"].nunique().reset_index()

cohort_counts = cohort_data.pivot(
    index="CohortMonth",
    columns="CohortIndex",
    values="CustomerID"
)

cohort_sizes = cohort_counts.iloc[:, 0]

retention = cohort_counts.divide(
    cohort_sizes, axis=0
) * 100

display(retention.round(2))

monthly_revenue = purchases.groupby(
    purchases["InvoiceDate"].dt.to_period("M")
)["Revenue"].sum()

monthly_customers = purchases.groupby(
    purchases["InvoiceDate"].dt.to_period("M")
)["CustomerID"].nunique()

revenue_per_customer_month = (
    monthly_revenue / monthly_customers
)

average_monthly_revenue_per_customer = (
    revenue_per_customer_month.mean()
)

assumed_lifetime_months = 6

estimated_clv = (
    average_monthly_revenue_per_customer
    * assumed_lifetime_months
)

print(
    "Average monthly revenue per customer:",
    round(average_monthly_revenue_per_customer, 2)
)

print("Assumed customer lifetime:", assumed_lifetime_months)

print("Estimated CLV:", round(estimated_clv, 2))

print("Customer spending summary:")

display(rfm["Monetary"].describe(
    percentiles=[0.25, 0.50, 0.75, 0.90, 0.95]
))

segment_summary = rfm.groupby("CustomerSegment").agg(
    Customers=("Monetary", "count"),
    AverageSpend=("Monetary", "mean"),
    MedianSpend=("Monetary", "median"),
    TotalRevenue=("Monetary", "sum"),
    AverageFrequency=("Frequency", "mean")
)

display(segment_summary)

q1 = rfm["Monetary"].quantile(0.25)
q3 = rfm["Monetary"].quantile(0.75)

iqr = q3 - q1

upper_bound = q3 + 1.5 * iqr

outliers = rfm[rfm["Monetary"] > upper_bound]

print("Upper Bound:", upper_bound)
print("Unusual high-spending customers:", len(outliers))

display(outliers.sort_values("Monetary", ascending=False).head(10))

outlier_revenue = outliers["Monetary"].sum()
total_customer_revenue = rfm["Monetary"].sum()

outlier_impact = (
    outlier_revenue / total_customer_revenue
) * 100

print("Revenue from unusual customers:", outlier_revenue)
print("Revenue contribution (%):", round(outlier_impact, 2))

top10 = rfm.sort_values("Monetary", ascending=False).head(10)

plt.figure(figsize=(10, 5))
plt.bar(top10.index.astype(str), top10["Monetary"])

plt.title("Top 10 Customers by Revenue")
plt.xlabel("Customer ID")
plt.ylabel("Revenue")
plt.xticks(rotation=45)

plt.tight_layout()
plt.show()

monthly_sales = purchases.groupby(
    purchases["InvoiceDate"].dt.to_period("M")
)["Revenue"].sum()

plt.figure(figsize=(12, 5))
plt.plot(monthly_sales.index.astype(str), monthly_sales.values, marker="o")

plt.title("Monthly Revenue Trend")
plt.xlabel("Month")
plt.ylabel("Revenue")

plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

plt.figure(figsize=(12, 6))

plt.imshow(retention, aspect="auto", cmap="YlGnBu")

plt.colorbar(label="Retention %")

plt.title("Customer Cohort Retention")
plt.xlabel("Months Since First Purchase")
plt.ylabel("Customer Cohort")

plt.xticks(
    range(len(retention.columns)),
    retention.columns
)

plt.yticks(
    range(len(retention.index)),
    retention.index.astype(str)
)

plt.tight_layout()
plt.show()

segment_counts = rfm["CustomerSegment"].value_counts()

plt.figure(figsize=(7, 5))
plt.bar(segment_counts.index, segment_counts.values)

plt.title("Customer Segments")
plt.xlabel("Segment")
plt.ylabel("Number of Customers")

plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 6))

plt.scatter(
    rfm["Frequency"],
    rfm["Monetary"],
    alpha=0.5
)

plt.title("Customer Purchase Frequency vs Spending")
plt.xlabel("Number of Orders")
plt.ylabel("Total Spending")

plt.tight_layout()
plt.show()

lifetime_scenarios = [3, 6, 12]

for months in lifetime_scenarios:
    clv = average_monthly_revenue_per_customer * months

    print(
        f"{months} months CLV:",
        round(clv, 2)
    )

# Net revenue includes negative quantity transactions
net_revenue = df["Revenue"].sum()

# Gross revenue from positive purchase transactions
gross_revenue = df.loc[
    df["Quantity"] > 0, "Revenue"
].sum()

print("Gross sales:", round(gross_revenue, 2))
print("Net sales including negative transactions:", round(net_revenue, 2))
print("Difference:", round(gross_revenue - net_revenue, 2))

revenue_original = rfm["Monetary"].sum()

revenue_without_outliers = rfm.loc[
    rfm["Monetary"] <= upper_bound, "Monetary"
].sum()

print("Revenue including all customers:", revenue_original)
print("Revenue without high-spending outliers:", revenue_without_outliers)

