# %% 4. revenue per customer, repeat rate, CLV
def estimate_clv(sales, returns, start, snapshot, ret_mult=1.0, cap=None, drop_ids=None,
                 margin=MARGIN, disc=DISC_MONTHLY, horizon=HORIZON):
    s = sales[(sales.invoice_date >= start) & (sales.invoice_date < snapshot)]
    rt = returns[(returns.invoice_date >= start) & (returns.invoice_date < snapshot)]
    if drop_ids is not None:
        s = s[~s.customer_id.isin(drop_ids)]
        rt = rt[~rt.customer_id.isin(drop_ids)]
    rt = rt[rt.customer_id.isin(s.customer_id.unique())]
    if cap is not None:
        s = s.assign(revenue=s.revenue.clip(upper=cap))

    act_, size_, ret_, _ = cohort_tables(s)
    R = ret_.to_numpy()
    n = size_.to_numpy()[:, None]
    seen = ~np.isnan(R)
    curve = list(np.where(seen, R * n, 0).sum(0) / np.where(seen, n, 0).sum(0))
    if len(curve) < horizon:        # window too short, extend with the average monthly decay
        ratios = [curve[k] / curve[k - 1] for k in range(2, len(curve)) if curve[k - 1] > 0]
        g = np.mean(ratios) if ratios else 0.8
        while len(curve) < horizon:
            curve.append(curve[-1] * g)
    curve = np.array(curve[:horizon])

    net = s.revenue.sum() - ret_mult * rt.revenue.sum()
    n_cust = s.customer_id.nunique()
    arpu = net / len(act_)                            # net revenue per active customer-month
    orders_per_cust = s.groupby("customer_id").invoice.nunique()
    return {
        "customers": n_cust,
        "repeat_rate": (orders_per_cust >= 2).mean(),
        "aov": s.groupby("invoice").revenue.sum().mean(),
        "rev_per_customer": net / n_cust,
        "arpu_month": arpu,
        "retention_m1": curve[1],
        "clv_12m": margin * arpu * (curve / (1 + disc) ** np.arange(horizon)).sum(),
    }


