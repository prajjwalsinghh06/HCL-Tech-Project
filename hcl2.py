# %% 2. feature pipeline (RFM etc), reusable for any snapshot date
def build_features(sales, snapshot, start=None, returns=None):
    t = sales[sales.invoice_date < snapshot]
    if start is not None:
        t = t[t.invoice_date >= start]
    orders = t.groupby(["customer_id", "invoice"]).agg(
        order_date=("invoice_date", "min"),
        order_value=("revenue", "sum"),
        units=("quantity", "sum"),
    ).reset_index()

    f = orders.groupby("customer_id").agg(
        first_order=("order_date", "min"),
        last_order=("order_date", "max"),
        frequency=("invoice", "nunique"),
        monetary=("order_value", "sum"),
        aov=("order_value", "mean"),
        units=("units", "sum"),
    )
    f["recency"] = (snapshot - f.last_order).dt.days
    f["tenure"] = (snapshot - f.first_order).dt.days
    f["units_per_order"] = f.units / f.frequency
    f["orders_per_month"] = f.frequency / np.maximum(f.tenure / 30.44, 1)
    f["log_monetary"] = np.log1p(f.monetary)
    f["is_repeat"] = f.frequency >= 2

    f["returns"] = 0.0
    if returns is not None:
        rt = returns[(returns.invoice_date < snapshot)]
        if start is not None:
            rt = rt[rt.invoice_date >= start]
        f["returns"] = rt.groupby("customer_id").revenue.sum().reindex(f.index).fillna(0)
    f["net_monetary"] = f.monetary - f.returns

    # scores 1-5, 5 is best
    f["r_score"] = pd.qcut(f.recency.rank(method="first", ascending=False), 5, labels=False) + 1
    f["f_score"] = pd.cut(f.frequency, [0, 1, 2, 4, 8, np.inf], labels=False) + 1
    f["m_score"] = pd.qcut(f.monetary.rank(method="first"), 5, labels=False) + 1

    r, fr = f.r_score, f.f_score
    conds = [(r >= 4) & (fr >= 4), (r >= 3) & (fr >= 3), (r >= 4) & (fr <= 2),
             (r <= 2) & (fr >= 3), (r <= 2) & (fr <= 2)]
    names = ["Champions", "Loyal", "Recent / low frequency", "At risk", "Hibernating"]
    f["segment"] = np.select(conds, names, default="Needs attention")
    return f, orders


