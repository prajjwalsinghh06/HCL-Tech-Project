def make_demo_data(n_cust=1800):
    r = np.random.default_rng(SEED)
    n_prod = 250
    codes = np.array([str(10000 + i) for i in range(n_prod)])
    prices = r.lognormal(1.0, 0.6, n_prod).round(2).clip(0.29)
    countries = np.array(["United Kingdom", "Germany", "France", "EIRE",
                          "Spain", "Netherlands", "Belgium", "Switzerland"])
    c_prob = [0.84, 0.04, 0.035, 0.025, 0.02, 0.015, 0.01, 0.015]
    season = np.array([0.8, 0.8, 0.9, 0.9, 0.95, 0.95, 0.9, 0.9, 1.1, 1.3, 1.6, 1.7])
    months = pd.date_range("2010-01-01", periods=24, freq="MS")
    last_day = pd.Timestamp("2011-12-31")
    rows = []
    inv_no = [500000]

    def new_order(cid, ctry, when, wholesale):
        inv_no[0] += 1
        inv = str(inv_no[0])
        k = int(r.integers(1, 9))
        idx = r.choice(n_prod, k, replace=False)
        qty = (r.poisson(3, k) + 1) * (12 if wholesale else 1)
        for i, q in zip(idx, qty):
            rows.append((inv, codes[i], f"ITEM {codes[i]}", int(q), when, prices[i], cid, ctry))
        if r.random() < 0.25:
            rows.append((inv, "POST", "POSTAGE", 1, when, 18.0, cid, ctry))
        # some customers send things back
        if not np.isnan(cid) and r.random() < 0.05:
            back = when + pd.Timedelta(days=int(r.integers(1, 20)))
            if back <= last_day:
                inv_no[0] += 1
                m = int(r.integers(1, k + 1))
                for i, q in list(zip(idx, qty))[:m]:
                    rows.append((f"C{inv_no[0]}", codes[i], f"ITEM {codes[i]}", -int(q), back,
                                 prices[i], cid, ctry))

    def random_time(month):
        d = int(r.integers(0, month.days_in_month))
        return month + pd.Timedelta(days=d, hours=int(r.integers(8, 18)), minutes=int(r.integers(0, 60)))

    ctry = r.choice(countries, n_cust, p=c_prob)
    w = np.linspace(1.3, 0.7, 24) * np.tile(season, 2)
    acq = r.choice(24, n_cust, p=w / w.sum())
    lam = r.gamma(1.2, 0.35, n_cust)
    churn = r.beta(2, 9, n_cust)
    whole = r.random(n_cust) < 0.02

    for c in range(n_cust):
        ch = churn[c]
        if months[acq[c]].month in (11, 12):      # christmas shoppers leave faster
            ch = min(ch * 1.6, 0.9)
        if whole[c]:
            ch *= 0.5
            lam[c] *= 1.5
        for m in range(acq[c], 24):
            n_ord = r.poisson(lam[c] * season[months[m].month - 1])
            if m == acq[c]:
                n_ord = max(n_ord, 1)
            for _ in range(n_ord):
                new_order(float(12000 + c), ctry[c], random_time(months[m]), whole[c])
            if r.random() < ch:
                break

    for _ in range(2500):                        # guest checkouts, no customer id
        new_order(np.nan, "United Kingdom", random_time(months[int(r.integers(0, 24))]), False)

    df = pd.DataFrame(rows, columns=["invoice", "stock_code", "description", "quantity",
                                     "invoice_date", "price", "customer_id", "country"])
    df = df.sort_values("invoice_date").reset_index(drop=True)

    # dirty rows, added on purpose
    df.loc[df.sample(25, random_state=2).index, "price"] = 0
    df.loc[df.sample(40, random_state=3).index, "description"] = np.nan
    neg = df.sample(20, random_state=4).copy()
    neg["invoice"] = [str(900000 + i) for i in range(20)]
    neg["quantity"] = -neg.quantity.abs()
    neg["customer_id"] = np.nan
    adj = pd.DataFrame({"invoice": [f"A90000{i}" for i in range(3)], "stock_code": "B",
                        "description": "Adjust bad debt", "quantity": 1,
                        "invoice_date": pd.Timestamp("2011-06-01"), "price": [-3000.0, -1200.0, -560.0],
                        "customer_id": np.nan, "country": "United Kingdom"})
    future = df.sample(3, random_state=6).copy()
    future["invoice_date"] = pd.Timestamp("2030-01-05")
    dup = df.sample(60, random_state=1)
    return pd.concat([df, neg, adj, future, dup], ignore_index=True)


