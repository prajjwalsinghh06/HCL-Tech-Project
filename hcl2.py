def tmean(x, p=0.1):
    x = np.sort(x.to_numpy())
    k = int(len(x) * p)
    return x[k:len(x) - k].mean()


def summarise(df, by):
    out = df.groupby(by).agg(
        customers=("monetary", "size"),
        revenue=("monetary", "sum"),
        mean=("monetary", "mean"),
        trimmed_mean=("monetary", tmean),
        p25=("monetary", lambda x: x.quantile(0.25)),
        median=("monetary", "median"),
        p75=("monetary", lambda x: x.quantile(0.75)),
        p90=("monetary", lambda x: x.quantile(0.90)),
        p99=("monetary", lambda x: x.quantile(0.99)),
        avg_orders=("frequency", "mean"),
        median_recency=("recency", "median"),
    )
    out["cust_share"] = out.customers / out.customers.sum()
    out["rev_share"] = out.revenue / out.revenue.sum()
    return out.sort_values("revenue", ascending=False)


