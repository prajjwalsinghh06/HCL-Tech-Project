# %% 3. monthly cohorts and retention
def cohort_tables(s):
    s = s.assign(month=s.invoice_date.dt.to_period("M"))
    first = s.groupby("customer_id").month.min().rename("cohort")
    act = s.groupby(["customer_id", "month"]).revenue.sum().reset_index().join(first, on="customer_id")
    act["age"] = (act.month.dt.year - act.cohort.dt.year) * 12 + (act.month.dt.month - act.cohort.dt.month)

    size = first.value_counts().sort_index()
    last = s.month.max()
    max_age = np.array([(last.year - c.year) * 12 + (last.month - c.month) for c in size.index])
    ages = range(max_age.max() + 1)

    active = act.pivot_table(index="cohort", columns="age", values="customer_id", aggfunc="nunique")
    revenue = act.pivot_table(index="cohort", columns="age", values="revenue", aggfunc="sum")
    active = active.reindex(index=size.index, columns=ages).fillna(0)
    revenue = revenue.reindex(index=size.index, columns=ages).fillna(0)
    retention = active.div(size, axis=0)
    for i, a in enumerate(max_age):               # ages we cannot observe yet are NaN, not 0
        retention.iloc[i, a + 1:] = np.nan
    return act, size, retention, revenue


